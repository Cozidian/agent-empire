#!/usr/bin/env python3
"""Collect upstream license texts for both supported, locked Linux dependency graphs."""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parent.parent
TARGETS = ('x86_64-unknown-linux-gnu', 'aarch64-unknown-linux-gnu')


def license_files(package):
    root = Path(package['manifest_path']).parent
    files = {p for p in root.rglob('*') if p.is_file() and p.name.lower().startswith(('license', 'licence', 'copying', 'notice', 'copyright'))}
    if package.get('license_file'):
        files.add(root / package['license_file'])
    # This crate's published archive omits the workspace-level licenses.
    if not files and (package['name'], package['version']) == ('dasp_sample', '0.11.0'):
        root = ROOT / 'third-party/dasp_sample-0.11.0'
        files = set(root.glob('LICENSE-*'))
    if not files:
        raise ValueError(f"Missing license texts: {package['name']} {package['version']}")
    return [(str(p.relative_to(root)), p.read_text(encoding='utf-8')) for p in sorted(files)]


def render(packages):
    inventory, documents = [], {}
    for p in sorted(packages, key=lambda p: (p['name'], p['version'])):
        name = f"{p['name']} {p['version']}"
        refs = []
        for filename, text in license_files(p):
            if not text.strip():
                raise ValueError(f'Empty license text: {name}/{filename}')
            digest = hashlib.sha256(text.encode()).hexdigest()
            entry = documents.setdefault(digest, {'text': text, 'users': []})
            entry['users'].append(f'{name}: {filename}')
            refs.append(digest)
        inventory.append((name, p.get('license') or 'see included texts', p.get('repository') or p['source'], refs))
    numbers = {digest: n for n, digest in enumerate(documents, 1)}
    out = ['THIRD-PARTY NOTICES\n',
           'Empire is MIT licensed. Its dependencies retain their own licenses and copyrights.\n'
           'This inventory includes runtime and build dependencies for both supported Linux targets,\n'
           'resolved with Cargo.lock and default features. Identical texts are printed once.\n'
           'Optional agent CLIs and the separately downloaded research runtime are not bundled.\n'
           'System shared libraries are supplied by your distribution. Rust standard-library\n'
           'attributions accompany release archives in RUST-THIRD-PARTY-NOTICES.html.\n\n'
           'Generated by python3 tools/third-party-notices.py; do not edit by hand.\n\nDEPENDENCIES\n']
    for name, license, source, refs in inventory:
        out.append(f"\n{name}\nLicense: {license}\nSource: {source}\nDocuments: {', '.join(str(numbers[r]) for r in refs)}\n")
    for digest, entry in documents.items():
        out.append(f"\n{'=' * 78}\nDOCUMENT {numbers[digest]}\n" + '\n'.join(entry['users']) + '\n\n' + entry['text'].rstrip() + '\n')
    return ''.join(out)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='fail if the committed notices are stale')
    args = parser.parse_args()
    packages = {}
    for target in TARGETS:
        data = json.loads(subprocess.check_output(['cargo', 'metadata', '--locked', '--format-version', '1', '--filter-platform', target], cwd=ROOT))
        resolved = {node['id'] for node in data['resolve']['nodes']}
        for p in data['packages']:
            if p['source'] and p['id'] in resolved:
                packages[p['id']] = p
    text = render(packages.values())
    path = ROOT / 'THIRD-PARTY-NOTICES.txt'
    if args.check:
        if not path.exists() or path.read_text() != text:
            raise SystemExit('Third-party notices are stale; run python3 tools/third-party-notices.py')
    else:
        path.write_text(text, encoding='utf-8')
    print(f'Checked notices for {len(packages)} locked dependencies')


if __name__ == '__main__':
    main()
